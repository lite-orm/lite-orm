package org.liteorm.benchmark;

import org.apache.ibatis.mapping.Environment;
import org.apache.ibatis.session.Configuration;
import org.apache.ibatis.session.SqlSessionFactory;
import org.apache.ibatis.session.SqlSessionFactoryBuilder;
import org.apache.ibatis.transaction.jdbc.JdbcTransactionFactory;
import org.h2.jdbcx.JdbcDataSource;

import javax.sql.DataSource;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;

final class BenchmarkSupport {

    private BenchmarkSupport() {
    }

    static DataSource dataSource() throws SQLException {
        JdbcDataSource dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1");
        try (var connection = dataSource.getConnection();
             var statement = connection.createStatement()) {
            statement.execute("CREATE TABLE benchmark_users (id BIGINT PRIMARY KEY, name VARCHAR(100), age INTEGER)");
            statement.execute("CREATE TABLE benchmark_batch (id BIGINT PRIMARY KEY, name VARCHAR(100))");
            statement.execute("CREATE TABLE benchmark_generated (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100))");
            connection.setAutoCommit(false);
            try (var insert = connection.prepareStatement(
                    "INSERT INTO benchmark_users (id, name, age) VALUES (?, ?, ?)")) {
                for (long id = 1; id <= 1_000; id++) {
                    insert.setLong(1, id);
                    insert.setString(2, "user-" + id);
                    insert.setInt(3, 20 + (int) (id % 50));
                    insert.addBatch();
                }
                insert.executeBatch();
            }
            connection.commit();
        }
        return dataSource;
    }

    static SqlSessionFactory myBatis(DataSource dataSource) {
        Environment environment = new Environment("benchmark", new JdbcTransactionFactory(), dataSource);
        Configuration configuration = new Configuration(environment);
        configuration.setMapUnderscoreToCamelCase(true);
        configuration.addMapper(MyBatisBenchmarkMapper.class);
        return new SqlSessionFactoryBuilder().build(configuration);
    }

    static List<BenchmarkRecord> batchRows() {
        List<BenchmarkRecord> rows = new ArrayList<>(100);
        for (long id = 1; id <= 100; id++) {
            rows.add(new BenchmarkRecord(id, "batch-" + id, 0));
        }
        return List.copyOf(rows);
    }

    static void clear(DataSource dataSource, String table) throws SQLException {
        try (var connection = dataSource.getConnection();
             var statement = connection.createStatement()) {
            statement.executeUpdate("DELETE FROM " + table);
        }
    }
}
